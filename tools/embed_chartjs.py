"""Regenerates include/chartjs_gz.h: a gzipped copy of Chart.js baked into the
firmware, so the dashboard works on the logger's no-internet access point.

Usage: python tools/embed_chartjs.py [version]   (default version below)
"""
import gzip
import pathlib
import sys
import urllib.request

VERSION = sys.argv[1] if len(sys.argv) > 1 else "4.4.1"
URL = f"https://cdn.jsdelivr.net/npm/chart.js@{VERSION}/dist/chart.umd.js"
OUT = pathlib.Path(__file__).resolve().parent.parent / "include" / "chartjs_gz.h"

src = urllib.request.urlopen(URL).read()
gz = gzip.compress(src, compresslevel=9, mtime=0)

lines = [
    "#pragma once",
    f"// Chart.js v{VERSION} (MIT License, https://www.chartjs.org), gzipped.",
    "// Generated by tools/embed_chartjs.py — do not edit by hand.",
    "#include <Arduino.h>",
    "",
    f"static const size_t CHARTJS_GZ_LEN = {len(gz)};",
    "static const uint8_t CHARTJS_GZ[] PROGMEM = {",
]
for i in range(0, len(gz), 20):
    lines.append("  " + ",".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
lines += ["};", ""]
OUT.write_text("\n".join(lines), newline="\n")
print(f"Wrote {OUT} ({len(src)} bytes -> {len(gz)} gzipped)")
